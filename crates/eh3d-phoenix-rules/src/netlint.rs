//! A check of the spelling of the names of the nets.
//!
//! A name that a program made up (`N$12`), two names that differ only in case (`GND` and `Gnd`),
//! a name with a space, a quote or a letter outside ASCII, a name that is too long for a netlist
//! and the half of a differential pair whose other half is missing are the usual causes of a net
//! that is joined by mistake, split by mistake or lost in a file of another program.
//! [`lint_net_names`] reads a list of names and gives what it finds in a fixed order; it does not
//! read a board and changes nothing.

use std::collections::BTreeMap;

/// The characters other than letters and digits that a name may hold.
pub const ALLOWED_PUNCTUATION: &str = "_-+.$/#~!*<>[]@%";

/// The limits of the check.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NetLintConfig {
    /// The most characters a name may have; 0 does not judge the length.
    pub max_len: usize,
    /// Whether a name made up by a program (`N$12`, `Net-(R1-Pad1)`, `unconnected-(U1-NC)`) is
    /// listed.
    pub flag_autogenerated: bool,
    /// Whether the half of a pair (`_P` and `_N`, `_DP` and `_DN`) with no other half is listed.
    pub check_pairs: bool,
}

impl Default for NetLintConfig {
    fn default() -> Self {
        NetLintConfig {
            max_len: 32,
            flag_autogenerated: true,
            check_pairs: true,
        }
    }
}

/// What is wrong with a name, in the order the issues of one name are given.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum NetIssueKind {
    /// The name is empty or only spaces.
    Empty,
    /// The name starts or ends with a space, or has a space inside.
    Space,
    /// The name has a character that is not a letter, a digit or one of
    /// [`ALLOWED_PUNCTUATION`].
    BadCharacter,
    /// The name has more than `max_len` characters.
    TooLong,
    /// The name is in the list more than once.
    Duplicate,
    /// The name is the same as another one if the case is ignored.
    CaseClash,
    /// The name is one that a program made up.
    Autogenerated,
    /// The name is the half of a pair and the other half is not in the list.
    PairMissing,
}

impl NetIssueKind {
    /// A stable word for the kind, for reports.
    pub fn word(self) -> &'static str {
        match self {
            NetIssueKind::Empty => "empty",
            NetIssueKind::Space => "space",
            NetIssueKind::BadCharacter => "bad_character",
            NetIssueKind::TooLong => "too_long",
            NetIssueKind::Duplicate => "duplicate",
            NetIssueKind::CaseClash => "case_clash",
            NetIssueKind::Autogenerated => "autogenerated",
            NetIssueKind::PairMissing => "pair_missing",
        }
    }
}

/// One thing found in the name of a net.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NetIssue {
    /// The name, as it is in the list.
    pub net: String,
    /// What is wrong.
    pub kind: NetIssueKind,
    /// A short sentence with the figure or the other name the issue is about.
    pub detail: String,
}

/// True for a name that a program made up.
pub fn is_autogenerated(name: &str) -> bool {
    if let Some(rest) = name.strip_prefix("N$") {
        return !rest.is_empty() && rest.bytes().all(|b| b.is_ascii_digit());
    }
    let lower = name.to_ascii_lowercase();
    lower.starts_with("net-(") || lower.starts_with("unconnected-(")
}

/// The other half of a pair and whether the name is the positive half; `None` for a name that
/// is not the half of a pair. Only the suffixes `_P`/`_N` and `_DP`/`_DN` count, in any case, and
/// only after a stem that is not empty.
pub fn pair_partner(name: &str) -> Option<String> {
    const SUFFIXES: [(&str, &str); 4] =
        [("_P", "_N"), ("_N", "_P"), ("_DP", "_DN"), ("_DN", "_DP")];
    let upper = name.to_ascii_uppercase();
    for (suffix, other) in SUFFIXES {
        if upper.len() > suffix.len()
            && upper.ends_with(suffix)
            && name.is_char_boundary(name.len() - suffix.len())
        {
            let stem = &upper[..upper.len() - suffix.len()];
            return Some(format!("{stem}{other}"));
        }
    }
    None
}

fn bad_character(name: &str) -> Option<char> {
    name.chars()
        .find(|c| !(c.is_ascii_alphanumeric() || ALLOWED_PUNCTUATION.contains(*c) || *c == ' '))
}

/// Checks the spelling of the names and gives what it finds, ordered by name (byte order) and
/// then by kind. The same list of names gives the same issues in the same order.
pub fn lint_net_names(names: &[String], config: &NetLintConfig) -> Vec<NetIssue> {
    let mut issues: Vec<NetIssue> = Vec::new();
    let mut count: BTreeMap<&str, usize> = BTreeMap::new();
    let mut by_lower: BTreeMap<String, Vec<&str>> = BTreeMap::new();
    for name in names {
        *count.entry(name.as_str()).or_insert(0) += 1;
    }
    for name in count.keys() {
        by_lower
            .entry(name.to_ascii_lowercase())
            .or_default()
            .push(name);
    }
    let upper_set: std::collections::BTreeSet<String> =
        count.keys().map(|n| n.to_ascii_uppercase()).collect();
    for (&name, &times) in &count {
        let mut push = |kind: NetIssueKind, detail: String| {
            issues.push(NetIssue {
                net: name.to_owned(),
                kind,
                detail,
            });
        };
        if name.trim().is_empty() {
            push(NetIssueKind::Empty, "the name has no characters".to_owned());
            continue;
        }
        if name.starts_with(' ') || name.ends_with(' ') || name.contains(' ') {
            push(NetIssueKind::Space, "the name has a space".to_owned());
        }
        if let Some(c) = bad_character(name) {
            push(
                NetIssueKind::BadCharacter,
                format!("the character U+{:04X} is not allowed", c as u32),
            );
        }
        let length = name.chars().count();
        if config.max_len > 0 && length > config.max_len {
            push(
                NetIssueKind::TooLong,
                format!("{length} characters, at most {}", config.max_len),
            );
        }
        if times > 1 {
            push(NetIssueKind::Duplicate, format!("listed {times} times"));
        }
        if let Some(group) = by_lower.get(&name.to_ascii_lowercase()) {
            if group.len() > 1 {
                let others: Vec<&str> = group.iter().copied().filter(|g| *g != name).collect();
                push(
                    NetIssueKind::CaseClash,
                    format!("same as {}", others.join(", ")),
                );
            }
        }
        if config.flag_autogenerated && is_autogenerated(name) {
            push(
                NetIssueKind::Autogenerated,
                "a name made up by a program".to_owned(),
            );
        }
        if config.check_pairs {
            if let Some(partner) = pair_partner(name) {
                if !upper_set.contains(&partner) {
                    push(
                        NetIssueKind::PairMissing,
                        format!("no net named like {partner}"),
                    );
                }
            }
        }
    }
    issues.sort_by(|a, b| a.net.cmp(&b.net).then(a.kind.cmp(&b.kind)));
    issues
}

#[cfg(test)]
mod tests {
    use super::*;

    fn names(list: &[&str]) -> Vec<String> {
        list.iter().map(|s| (*s).to_owned()).collect()
    }

    fn kinds(list: &[&str], config: &NetLintConfig) -> Vec<(String, NetIssueKind)> {
        lint_net_names(&names(list), config)
            .into_iter()
            .map(|i| (i.net, i.kind))
            .collect()
    }

    #[test]
    fn clean_names_give_nothing() {
        let found = lint_net_names(
            &names(&["GND", "+3V3", "SDA", "USB_DP", "USB_DN", "CLK_P", "CLK_N"]),
            &NetLintConfig::default(),
        );
        assert!(found.is_empty(), "{found:?}");
    }

    #[test]
    fn empty_and_space_names() {
        let found = kinds(&["", "  ", "A B", " X"], &NetLintConfig::default());
        assert!(found.contains(&(String::new(), NetIssueKind::Empty)));
        assert!(found.contains(&("  ".to_owned(), NetIssueKind::Empty)));
        assert!(found.contains(&("A B".to_owned(), NetIssueKind::Space)));
        assert!(found.contains(&(" X".to_owned(), NetIssueKind::Space)));
    }

    #[test]
    fn bad_characters_are_named() {
        let found = lint_net_names(
            &names(&["A;B", "caf\u{e9}", "Q\"1"]),
            &NetLintConfig::default(),
        );
        assert_eq!(found.len(), 3);
        assert!(found.iter().all(|i| i.kind == NetIssueKind::BadCharacter));
        assert!(found.iter().any(|i| i.detail.contains("U+00E9")));
    }

    #[test]
    fn length_limit_counts_characters_not_bytes() {
        let config = NetLintConfig {
            max_len: 4,
            ..NetLintConfig::default()
        };
        assert!(kinds(&["ABCD"], &config).is_empty());
        assert_eq!(
            kinds(&["ABCDE"], &config),
            vec![("ABCDE".to_owned(), NetIssueKind::TooLong)]
        );
        let off = NetLintConfig {
            max_len: 0,
            ..NetLintConfig::default()
        };
        assert!(kinds(&["A_VERY_LONG_NET_NAME_THAT_GOES_ON_AND_ON"], &off).is_empty());
    }

    #[test]
    fn duplicates_and_case_clashes() {
        let found = kinds(&["GND", "GND", "Gnd", "VCC"], &NetLintConfig::default());
        assert!(found.contains(&("GND".to_owned(), NetIssueKind::Duplicate)));
        assert!(found.contains(&("GND".to_owned(), NetIssueKind::CaseClash)));
        assert!(found.contains(&("Gnd".to_owned(), NetIssueKind::CaseClash)));
        assert!(!found.iter().any(|(n, _)| n == "VCC"));
    }

    #[test]
    fn autogenerated_names() {
        assert!(is_autogenerated("N$12"));
        assert!(!is_autogenerated("N$"));
        assert!(!is_autogenerated("N$1a"));
        assert!(is_autogenerated("Net-(R1-Pad1)"));
        assert!(is_autogenerated("unconnected-(U1-NC)"));
        assert!(!is_autogenerated("NET1"));
        let off = NetLintConfig {
            flag_autogenerated: false,
            ..NetLintConfig::default()
        };
        assert!(kinds(&["N$12"], &off).is_empty());
        assert_eq!(
            kinds(&["N$12"], &NetLintConfig::default()),
            vec![("N$12".to_owned(), NetIssueKind::Autogenerated)]
        );
    }

    #[test]
    fn pair_halves() {
        assert_eq!(pair_partner("CLK_P").as_deref(), Some("CLK_N"));
        assert_eq!(pair_partner("clk_n").as_deref(), Some("CLK_P"));
        assert_eq!(pair_partner("USB_DP").as_deref(), Some("USB_DN"));
        assert_eq!(pair_partner("_P"), None);
        assert_eq!(pair_partner("GND"), None);
        let found = kinds(&["CLK_P", "SDA_N", "SDA_P"], &NetLintConfig::default());
        assert_eq!(found, vec![("CLK_P".to_owned(), NetIssueKind::PairMissing)]);
        let off = NetLintConfig {
            check_pairs: false,
            ..NetLintConfig::default()
        };
        assert!(kinds(&["CLK_P"], &off).is_empty());
        // The other half may differ in case.
        assert!(kinds(&["Clk_P", "CLK_n"], &NetLintConfig::default()).is_empty());
    }

    #[test]
    fn order_is_by_name_then_kind() {
        let found = lint_net_names(&names(&["b b", "A;", "N$1"]), &NetLintConfig::default());
        let order: Vec<&str> = found.iter().map(|i| i.net.as_str()).collect();
        let mut sorted = order.clone();
        sorted.sort_unstable();
        assert_eq!(order, sorted);
    }

    #[test]
    fn words_are_all_different() {
        let all = [
            NetIssueKind::Empty,
            NetIssueKind::Space,
            NetIssueKind::BadCharacter,
            NetIssueKind::TooLong,
            NetIssueKind::Duplicate,
            NetIssueKind::CaseClash,
            NetIssueKind::Autogenerated,
            NetIssueKind::PairMissing,
        ];
        let words: std::collections::BTreeSet<&str> = all.iter().map(|k| k.word()).collect();
        assert_eq!(words.len(), all.len());
    }
}
